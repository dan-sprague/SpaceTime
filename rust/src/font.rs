/// Slot of `c` in the atlas; unknown characters fall back to space (0).
pub fn glyph_index(c: char) -> usize {
    let c = c.to_ascii_uppercase();
    CHARSET.chars().position(|k| k == c).unwrap_or(0)
}

/// The font as a flat `[glyph][row][col]` array of 0.0/1.0, row-major within a
/// glyph, ready to upload as a Metal buffer.
pub fn atlas() -> Vec<f32> {
    let mut a = vec![0.0f32; ART.len() * GLYPH_W * GLYPH_H];
    for (g, rows) in ART.iter().enumerate() {
        for (r, row) in rows.iter().enumerate() {
            for (c, ch) in row.chars().enumerate() {
                if ch == '#' {
                    a[(g * GLYPH_H + r) * GLYPH_W + c] = 1.0;
                }
            }
        }
    }
    a
}

pub fn glyph_count() -> usize { ART.len() }

/// Print every glyph as ASCII so the shapes can be checked without a window.
/// Run with `--fontdump`.
pub fn dump() {
    for (i, c) in CHARSET.chars().enumerate() {
        println!("[{c}]");
        for r in 0..GLYPH_H {
            let row: String = ART[i][r].chars()
                .map(|ch| if ch == '#' { '#' } else { ' ' }).collect();
            println!("  {row}");
        }
    }
    // Sanity: every glyph row must be exactly GLYPH_W wide.
    for (i, rows) in ART.iter().enumerate() {
        for (r, row) in rows.iter().enumerate() {
            assert_eq!(row.chars().count(), GLYPH_W,
                       "glyph {i} row {r} is not {GLYPH_W} wide");
        }
    }
    assert_eq!(ART.len(), CHARSET.chars().count(),
               "ART and CHARSET length mismatch");
    println!("{} glyphs, all {GLYPH_W}x{GLYPH_H}", ART.len());
}
