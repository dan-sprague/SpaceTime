//! A tiny 5x7 bitmap font for the on-screen menu, authored as ASCII art so the
//! source is its own proof: each glyph is seven rows of five characters, '#'
//! set and '.' clear. `atlas()` packs them into a flat GPU-friendly table and
//! `dump()` prints them back out for eyeball verification without a display.

